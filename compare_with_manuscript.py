#!/usr/bin/env python3
"""Compare a regenerated run of the pipeline with the manuscript.

What it checks
  A. archived results/ and src/tables.json  vs  the files regenerated by reproduce_all.py
  B. every table body / number in src/tables.json  vs  the LaTeX source of the manuscript
  C. headline numbers quoted in the abstract and text  vs  the regenerated results
  D. regenerated figures  vs  the figures used in the manuscript (pixel similarity,
     each regenerated figure is matched to its best manuscript figure automatically)

Usage (from the repository root, after `python reproduce_all.py`):
    python compare_with_manuscript.py --manuscript path/to/main.tex \
        --manuscript-figs path/to/figures_png --archived path/to/archived_repo --out report.md

Needs only numpy and Pillow (installed with matplotlib). The manuscript itself is not part of the
public repository, so --manuscript and --manuscript-figs point to your local copy.
"""
import argparse, json, os, re, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument('--manuscript', required=True, help='main.tex of the manuscript')
ap.add_argument('--manuscript-figs', required=True, help='folder with the manuscript figures (PNG)')
ap.add_argument('--archived', required=True, help='folder of the archived (reference) repository copy')
ap.add_argument('--out', default=os.path.join(HERE, 'comparison_report.md'))
a = ap.parse_args()

SRC = os.path.join(HERE, 'src'); RES = os.path.join(HERE, 'results'); FIG = os.path.join(HERE, 'figures')
ASRC = os.path.join(a.archived, 'src'); ARES = os.path.join(a.archived, 'results')
tex = open(a.manuscript, encoding='utf-8').read()
out = []; fails = 0
def P(s=''): print(s); out.append(s)
def flag(ok):
    global fails; fails += (not ok); return 'OK  ' if ok else 'FAIL'

# ------------------------------------------------------------------ A. archived vs regenerated
P('# Comparison of the regenerated run with the manuscript\n')
P('## A. Regenerated results vs archived results\n')
SKIP = {'sec', 'time', 't', 'wall', 'secs'}
def walk(x, y, path, bad, tol):
    if isinstance(x, dict) and isinstance(y, dict):
        for k in x:
            if k in SKIP or k in ('pareto', 'pareto_n_eval'): continue  # Pareto front: ordering of a sampled set, compared in Figure 6b/5b only
            if k not in y: bad.append((path + '/' + k, 'missing in regenerated')); continue
            walk(x[k], y[k], path + '/' + k, bad, tol)
    elif isinstance(x, (list, tuple)) and isinstance(y, (list, tuple)):
        if len(x) != len(y): bad.append((path, f'length {len(x)} vs {len(y)}')); return
        for i, (u, v) in enumerate(zip(x, y)): walk(u, v, f'{path}[{i}]', bad, tol)
    elif isinstance(x, (int, float)) and isinstance(y, (int, float)) and not isinstance(x, bool):
        if not np.isclose(x, y, rtol=tol, atol=1e-12): bad.append((path, f'{x!r} vs {y!r}'))
    elif x != y: bad.append((path, f'{str(x)[:40]!r} vs {str(y)[:40]!r}'))
# deterministic files must agree to 1e-6; files that depend on random forests / gradient boosting / Sobol sampling
# (stage2, stage5 Sobol part, stage6, stage8) can move in the 3rd-4th digit between runs, so they get a loose
# tolerance and the largest deviation is reported. cheb.json depends on a solver tolerance cut-off and is informational.
STRICT = {'stage7.json': 1e-6, 'val.json': 1e-6, 'caps.json': 1e-6}
LOOSE = {'stage2.json': 0.1, 'stage5.json': 0.1, 'stage6.json': 0.1, 'stage8.json': 0.1}
def maxdev(x, y):
    if isinstance(x, dict) and isinstance(y, dict): return max([maxdev(x[k], y[k]) for k in x if k in y and k not in SKIP and k not in ('pareto', 'pareto_n_eval')] or [0])
    if isinstance(x, (list, tuple)) and isinstance(y, (list, tuple)) and len(x) == len(y): return max([maxdev(u, v) for u, v in zip(x, y)] or [0])
    if isinstance(x, (int, float)) and isinstance(y, (int, float)) and not isinstance(x, bool): return abs(x - y) / max(abs(x), 1e-3)
    return 0
for f in list(STRICT) + list(LOOSE) + ['cheb.json']:
    p1, p2 = os.path.join(ARES, f), os.path.join(RES, f)
    if not (os.path.exists(p1) and os.path.exists(p2)): P(f'- {f}: skipped (not present in both)'); continue
    x, y = json.load(open(p1)), json.load(open(p2)); bad = []
    if f == 'cheb.json':
        P(f'- INFO {f}: baseline rel. error {x["baseline"]["rel"]:.1e} vs {y["baseline"]["rel"]:.1e}; optimum {x["optimum"]["rel"]:.1e} vs {y["optimum"]["rel"]:.1e}; LHS cases compared {x["n_lhs_compared"]} vs {y["n_lhs_compared"]}; max rel. LHS difference {x["max_rel_lhs"]:.1e} vs {y["max_rel_lhs"]:.1e}'); continue
    tol = STRICT.get(f, LOOSE.get(f)); walk(x, y, '', bad, tol)
    kind = 'deterministic' if f in STRICT else 'stochastic ML stage, rtol 0.1'
    P(f'- {flag(not bad)} {f} ({kind}): {len(bad)} entries outside tolerance; largest relative deviation {maxdev(x, y):.2e}' + ''.join(f'\n    - {p}: {m}' for p, m in bad[:5]))
d1 = {(r['tag'], r['seed']): r for r in map(json.loads, open(os.path.join(ARES, 'de_results.jsonl')))}
d2 = {(r['tag'], r['seed']): r for r in map(json.loads, open(os.path.join(RES, 'de_results.jsonl')))}
bad = [k for k in d1 if k not in d2 or not np.isclose(d1[k]['Nu'], d2[k]['Nu'], rtol=1e-6) or not np.allclose(d1[k]['x'], d2[k]['x'], rtol=1e-6)]
P(f'- {flag(not bad)} de_results.jsonl: {len(d1)} optimization runs, {len(bad)} differ in Nu or design vector')
t1 = json.load(open(os.path.join(ASRC, 'tables.json'))); t2 = json.load(open(os.path.join(SRC, 'tables.json')))
bad = [k for k in t1 if t1[k] != t2.get(k)]
P(f'- INFO tables.json: {len(t1)} entries, {len(bad)} differ in the last printed digit ({bad[:12]}); these come from the stochastic ML stages. Section B shows whether any of them is quoted in the manuscript.')
l1 = np.loadtxt(os.path.join(ARES, 'lhs_dataset.csv'), delimiter=',', skiprows=1); l2 = (np.loadtxt(os.path.join(RES, 'lhs_dataset.csv'), delimiter=',', skiprows=1) if os.path.exists(os.path.join(RES, 'lhs_dataset.csv')) else np.load(os.path.join(SRC, 'lhs_raw.npy')))
P(f'- {flag(l1.shape == l2.shape and np.allclose(l1, l2, rtol=1e-6, atol=1e-6, equal_nan=True))} lhs_dataset (csv is rounded to 9 digits; regenerated src/lhs_raw.npy if the csv is absent): shape {l1.shape}, max |diff| = {np.nanmax(np.abs(l1 - l2)):.2e}')

# ------------------------------------------------------------------ B. tables.json vs manuscript source
P('\n## B. Regenerated tables.json vs the manuscript LaTeX source\n')
norm = lambda s: re.sub(r'\s+', '', s)
T = norm(tex); found = {}; miss = {}
for k, v in t2.items():
    for row in [r for r in str(v).split('\n') if r.strip()]:
        (found if norm(row) in T else miss).setdefault(k, []).append(row)
nf = sum(map(len, found.values())); nm = sum(map(len, miss.values()))
P(f'- {nf} of {nf + nm} table rows / numbers are found verbatim in the manuscript source.')
only_unused = [k for k in miss if k not in found and not re.search(re.escape(k), tex)]
P(f'- Entries that are archived but not used in the manuscript text ({len(miss)} keys, {nm} rows): ' + ', '.join(sorted(miss)))
ML_KEYS = {'T_cv', 'T_t10'}  # cross-validation tables: last printed digit moves between runs (random folds)
partial_ml = [k for k in miss if k in found and k in ML_KEYS]
partial = [k for k in miss if k in found and k not in ML_KEYS]
P(f'- {flag(not partial)} keys that are only partly found in the manuscript (a real mismatch): {partial or "none"}')
for k in partial_ml: P(f'- INFO {k}: {len(miss[k])} row(s) differ from the manuscript in the last printed digit after the clean re-run (random cross-validation folds); the manuscript keeps the archived-run values')
for k in partial:
    for r in miss[k][:6]: P(f'    - {k}: regenerated row not in manuscript: {r[:110]}')

# ------------------------------------------------------------------ C. headline numbers
P('\n## C. Headline numbers in the abstract and text vs regenerated results\n')
v = json.load(open(os.path.join(RES, 'val.json'))); o = json.load(open(os.path.join(RES, 'stage5.json'))); s2 = json.load(open(os.path.join(RES, 'stage2.json')))
de = [json.loads(l) for l in open(os.path.join(RES, 'de_results.jsonl'))]
nu_ref = np.array([r['Nu'] for r in de if r['tag'] == 'ref'])
cap15 = [r['Nu'] for r in de if r['tag'] == 'cap15'][0]
lhs = l2; nconv = int(lhs[:, -1].sum()); nfail = len(lhs) - nconv
abstract = re.search(r'\\begin\{abstract\}(.*?)\\end\{abstract\}', tex, re.S).group(1)
def num(pattern, text=abstract, g=1):
    m = re.search(pattern, text, re.S); return float(m.group(g)) if m else float('nan')
claims = [
 ('baseline Nu (abstract: raises from)', num(r'from (\d+(?:\.\d+)?) to [\d.]+'), v['baseline']['Nu'], 5e-3),
 ('optimum Nu (abstract: to)', num(r'from [\d.]+ to (\d+(?:\.\d+)?)'), o['opt'][2], 5e-3),
 ('gain factor (abstract: n-fold)', num(r'\((\d+(?:\.\d+)?)-fold\)'), o['ratio'], 2e-2),
 ('ten-seed minimum', num(r'Ten seeds give (\d+(?:\.\d+)?) to'), nu_ref.min(), 5e-3),
 ('ten-seed maximum', num(r'Ten seeds give [\d.]+ to (\d+(?:\.\d+)?)'), nu_ref.max(), 5e-3),
 ('non-converged cases (abstract)', num(r'all (\d+) non-converged'), nfail, 0),
 ('converged above the Du Sr bound', num(r'the (\d+) cases that converge above'), float(t2['nviol_conv']), 0),
 ('cross-validated R2 of Nu_x (abstract)', num(r'cross-validated \$R\^2\$ of (\d+(?:\.\d+)?)'), s2['cv_gbt']['Nu']['r2'][0], 6e-3),
 ('share kept with f_w<=1.5 (abstract, %)', num(r'keeps (\d+)\\%'), 100 * cap15 / o['opt'][2], 1e-2),
]
for n, ms, rg, tol in claims:
    ok = np.isfinite(ms) and abs(ms - rg) <= max(tol * abs(rg), 1e-12 if tol == 0 else 0)
    P(f'- {flag(ok)} {n}: manuscript {ms:g}, regenerated {rg:.4g}')

# ------------------------------------------------------------------ D. figures
P('\n## D. Regenerated figures vs manuscript figures\n')
def load(p, n=96):
    im = Image.open(p).convert('RGBA'); bg = Image.new('RGBA', im.size, (255, 255, 255, 255)); im = Image.alpha_composite(bg, im).convert('L')
    # blur + coarse box resize: figures differ by a few pixels in size between runs, which a fine grid would punish
    from PIL import ImageFilter
    return np.asarray(im.filter(ImageFilter.GaussianBlur(max(im.size) / 200)).resize((n, n), Image.BOX), dtype=float) / 255.0
def sim(x, y):
    x0, y0 = x - x.mean(), y - y.mean(); ncc = (x0 * y0).sum() / (np.sqrt((x0 ** 2).sum() * (y0 ** 2).sum()) + 1e-12)
    return ncc, np.abs(x - y).mean()
mfigs = {f[:-4]: load(os.path.join(a.manuscript_figs, f)) for f in sorted(os.listdir(a.manuscript_figs)) if f.lower().endswith('.png')}
rows = []
for f in sorted(os.listdir(FIG)):
    if not f.lower().endswith('.png') or f.startswith('graphical'): continue
    g = load(os.path.join(FIG, f)); sc = {k: sim(g, m) for k, m in mfigs.items()}
    best = max(sc, key=lambda k: sc[k][0]); ncc, mad = sc[best]
    # regenerated figure vs the archived figure of the same file name (should be identical up to rendering)
    ap_ = os.path.join(a.archived, 'figures', f); ncc_a = sim(g, load(ap_))[0] if os.path.exists(ap_) else float('nan')
    rows.append((f[:-4], best, ncc, mad, ncc_a))
P('| regenerated figure | best manuscript figure | correlation | mean abs. diff | vs archived copy |\n|---|---|---|---|---|')
for n, b, ncc, mad, nca in rows:
    P(f'| {n} | {b} | {ncc:.4f} | {mad:.4f} | {nca:.4f} |')
STOCH = {'Figure_5b': 'Pareto front of a sampled set', 'Figure_11': 'conformal calibration with random splits'}
low = [r for r in rows if r[2] < 0.98 and r[0] not in STOCH]
P(f'\n- {flag(not low)} deterministic figures whose best manuscript match has correlation below 0.98: {[r[0] for r in low] or "none"}')
for r in rows:
    if r[0] in STOCH: P(f'- INFO {r[0]} ({STOCH[r[0]]}) depends on random sampling: correlation {r[2]:.2f}; same axes and trend, individual points differ (check by eye)')
used = {r[1] for r in rows}
P(f'- manuscript figures not matched by any regenerated figure: {sorted(set(mfigs) - used) or "none"} (figures drawn without the pipeline, for example the schematic, or exported at another size)')

P(f'\n**Result: {fails} check(s) failed.**' if fails else '\n**Result: all checks passed.**')
open(a.out, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
sys.exit(1 if fails else 0)
